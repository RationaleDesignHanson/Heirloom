            sourceURL: "https://www.allrecipes.com/recipe/12345/chocolate-chip-cookies",
            sourceAttribution: "AllRecipes.com",
            generation: 0,
            cachedMetrics: AggregatedMetrics(
                totalShares: 15,
                totalCooks: 42,
                averageRating: 4.5,
                ratingCount: 12
            )
        )
    }

    /// Sample provenance for a shared recipe
    static func sampleShared() -> ProvenanceMetadata {
        ProvenanceMetadata(
            sourceType: .shared,
            sourceAttribution: "Originally from AllRecipes.com",
            generation: 1,
            parentShareID: "share-12345",
            sharedByName: "Sarah M.",
            cachedMetrics: AggregatedMetrics(
                totalShares: 3,
                totalCooks: 8,
                averageRating: 5.0,
                ratingCount: 2
            )
        )
    }
}
