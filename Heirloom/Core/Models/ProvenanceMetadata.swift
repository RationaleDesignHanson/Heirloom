        ProvenanceMetadata(
            sourceType: .userCreated,
            sourceAttribution: "My Recipe",
            generation: 0
        )
    }

    /// Sample provenance for an imported recipe
    static func sampleImported() -> ProvenanceMetadata {
        ProvenanceMetadata(
